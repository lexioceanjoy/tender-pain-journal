import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const variants = ['female', 'male'];
const maps = {};

for (const variant of variants) {
  const source = await readFile(resolve(root, `vendor/choir-body-map/maps/choirbodymap_${variant}.html`), 'utf8');
  const regions = [...source.matchAll(/<area data-key="([^"]+)" title="([^"]+)" href="" shape="poly" coords="([^"]+)" \/>/g)]
    .map(([, sourceKey, sourceTitle, coords]) => ({
      id: `choir-${sourceKey}`,
      sourceKey,
      sourceTitle,
      label: patientLabel(sourceTitle),
      points: coords.split(',').reduce((pairs, value, index, values) => {
        if (index % 2 === 0) pairs.push(`${value},${values[index + 1]}`);
        return pairs;
      }, []).join(' ')
    }));

  if (regions.length !== 74) throw new Error(`${variant} map contains ${regions.length} regions; expected 74`);
  maps[variant] = {
    front: regions.filter(({ sourceKey }) => sourceKey.startsWith('f')),
    back: regions.filter(({ sourceKey }) => sourceKey.startsWith('b'))
  };
}

for (const view of ['front', 'back']) {
  const femaleKeys = maps.female[view].map(({ sourceKey }) => sourceKey).join(',');
  const maleKeys = maps.male[view].map(({ sourceKey }) => sourceKey).join(',');
  if (femaleKeys !== maleKeys) throw new Error(`${view} region keys differ between outlines`);
}

const output = `// Generated by scripts/generate-choir-regions.mjs from the attributed source snapshot.
// Do not hand-edit region geometry.

export type ChoirOutline = 'female' | 'male';
export type ChoirView = 'front' | 'back';

export type ChoirRegion = {
  id: string;
  sourceKey: string;
  sourceTitle: string;
  label: string;
  points: string;
};

export const choirRegions: Record<ChoirOutline, Record<ChoirView, ChoirRegion[]>> = ${JSON.stringify(maps, null, 2)};
`;

await writeFile(resolve(root, 'src/features/body-map/choirRegions.generated.ts'), output);

function patientLabel(title) {
  const match = title.match(/^(.+) \((front|back|palm|top|bottom)-(right|left)\)$/);
  if (!match) throw new Error(`Unexpected CHOIR title: ${title}`);
  const [, part, surface, side] = match;
  const names = {
    Cranium: surface === 'front' ? 'front and top of head' : 'back and top of head',
    Face: 'face',
    Head: 'back of head',
    Neck: `${surface} of neck`,
    Shoulder: `${surface} of shoulder`,
    Chest: 'chest',
    Bicep: `${surface} upper arm`,
    Elbow: 'elbow',
    Forearm: `${surface} forearm`,
    Abdomen: 'abdomen',
    Wrist: 'wrist',
    Hip: `${surface} hip`,
    Pubic: 'groin and pubic area',
    Hand: `${surface} of hand`,
    'Upper Leg': `${surface} upper leg`,
    Knee: `${surface} of knee`,
    'Lower Leg': `${surface} lower leg`,
    Ankle: `${surface} of ankle`,
    Foot: `${surface} of foot`,
    'Upper Back': 'upper back',
    'Middle Back': 'middle back',
    'Lower Back': 'lower back',
    Buttocks: 'buttock'
  };
  const name = names[part];
  if (!name) throw new Error(`No patient label mapping for: ${title}`);
  return `${side[0].toUpperCase()}${side.slice(1)} ${name}`;
}
